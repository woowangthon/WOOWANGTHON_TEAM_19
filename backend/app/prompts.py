def grade_band_of(grade: int | None) -> str:
    """가입 학년(1~12) → 학년대(명세 부록 D). 모르면 초5-6."""
    if grade is None:
        return "초5-6"
    if grade <= 2:
        return "초1-2"
    if grade <= 4:
        return "초3-4"
    if grade <= 6:
        return "초5-6"
    if grade <= 9:
        return "중1-3"
    return "고1-3"


def grade_band_now(
    grade: int | None, signup_at: datetime | None, now: datetime, fallback: str
) -> str:
    """가입 학년을 학년도만큼 올린 학년대(명세 4.12-5 UG1). 학년이 없으면(체험 세트) 학생 행의 학년대."""
    g = current_grade(grade, signup_at, now)
    return grade_band_of(g) if g is not None else fallback


