@dataclass(frozen=True)
class PromptInput:
    phase: Literal["study", "chat", "bridge"]
    grade_band: str
    honorific: str  # hyung / unni / friend
    style: str  # EBSP / EQLC / DQSC
    polite: bool
    problem_text: str
    hint1: str
    hint2: str
    solution: str
    hint_level: int
    judge: Literal["correct", "wrong"] | None
    turns: list[dict[str, str]] = field(default_factory=list)  # PII 치환본만


@dataclass(frozen=True)
class Prompt:
    system: str
    turns: list[dict[str, str]]


def _allowed_hint(inp: PromptInput) -> str:
    if inp.hint_level >= 3:
        return f"풀이 — {inp.solution}"
    if inp.hint_level == 2:
        return inp.hint2
    if inp.hint_level == 1:
        return inp.hint1
    return "없음(아직 힌트를 쓰지 않는다)"


def _fixed(inp: PromptInput) -> list[str]:
    """문제·판정과 무관한 앞부분. 같은 (단계, 스타일, 호칭, 말투)면 글자까지 같다."""
    style = inp.style if inp.style in STYLE_CARD else "EBSP"
    who = HONORIFIC.get(inp.honorific, HONORIFIC["friend"])
    speech = "존댓말로 말한다." if inp.polite else "반말로 말한다."
    examples = [f"- 아이: {child}\n  너: {mentor}" for child, mentor in FEWSHOT[style][inp.phase]]
    return [
        ROLE_LINE[inp.phase].format(grade=inp.grade_band, who=who) + ".",
        '아이를 "너"라고 부르고 이름을 묻지 않는다.',
        "[말투]",
        *STYLE_CARD[style],
        speech,
        "[규칙]",
        *RULES[inp.phase],
        "[예시 대화] 말투만 참고한다. 예시 속 숫자·이야기는 지금 대화와 상관없다. "
        "예시는 반말이지만 말투 규칙이 예시보다 우선이다. [정답]/[오답]은 서버 판정 표시다.",
        *examples,
    ]


def build_prompt(inp: PromptInput) -> Prompt:
    lines = _fixed(inp)
    if inp.phase == "study":
        lines += [
            "[지금 문제]",
            f"문제: {inp.problem_text}",
            f"현재 힌트 단계: {inp.hint_level} / 이 단계에서 써도 되는 힌트: {_allowed_hint(inp)}",
            f"서버 판정: {JUDGE_LINE[inp.judge]}",
        ]
    return Prompt(system="\n".join(lines), turns=list(inp.turns))
